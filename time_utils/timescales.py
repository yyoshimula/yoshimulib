def leap_s() -> np.ndarray:
    """
    # calculating insertion date of leap seconds

    Returns
    -------
    leap_jd : np.ndarray
        n x 2 array with [Julian day, cumulative leap seconds]

    Notes
    -----
    leap_s() returns the leap second table.
    Use the result as input to dat() function.

    References
    ----------
    Vallado, D. A., & McClain, W. D. (2001). Fundamentals of Astrodynamics
    and Applications. Springer Science & Business Media. 4th edition.

    Revisions
    ---------
    20230605  y.yoshimura, y.yoshimula@gmail.com

    See also
    --------
    dat
    """
    leap_jd = np.zeros((len(LEAP_SECONDS_DATA), 2))

    for i, (y, m, d, ls) in enumerate(LEAP_SECONDS_DATA):
        leap_jd[i, 0] = gc2jd(y, m, d, 0, 0, 0)
        leap_jd[i, 1] = ls

    return leap_jd


