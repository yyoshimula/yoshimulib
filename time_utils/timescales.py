def dat(jd: float, leap_jd: np.ndarray) -> float:
    """
    # calculating delta_AT (= TAI - UTC)

    Parameters
    ----------
    jd : float
        Julian day, day
    leap_jd : np.ndarray
        n x 2 array with [Julian day, cumulative leap seconds]
        (output from leap_s())

    Returns
    -------
    delta_at : float
        TAI - UTC in seconds

    Notes
    -----
    Execute leap_s() first and use its result as leap_jd argument.

    References
    ----------
    Vallado, D. A., & McClain, W. D. (2001). Fundamentals of Astrodynamics
    and Applications. Springer Science & Business Media. 4th edition.

    Revisions
    ---------
    20230605  y.yoshimura, y.yoshimula@gmail.com

    See also
    --------
    leap_s
    """
    # Search from most recent backwards
    i = len(leap_jd) - 1
    while i >= 0 and jd < leap_jd[i, 0]:
        i -= 1

    if i < 0:
        # Before 1972-01-01
        delta_at = 10.0
    else:
        delta_at = leap_jd[i, 1] + 10.0

    return delta_at


