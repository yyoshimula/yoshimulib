def ut2tt(jd: float | np.ndarray) -> float | np.ndarray:
    """
    # calculating the difference from UT1 to Terrestrial time (TT)
    Compute delta_t = TT - UT1

    Parameters
    ----------
    jd : float or np.ndarray
        Julian day, day

    Returns
    -------
    dt : float or np.ndarray
        delta_t (TT - UT1), seconds

    Notes
    -----
    delta_t = TT - UT1
            = TAI + 32.184 - UT1
            = UTC + delta_AT + 32.184 - UT1
            = delta_AT + 32.184 - delta_UT1

    References
    ----------
    Fred Espenak and Jean Meeus, "FIVE MILLENNIUM CANON OF SOLAR ECLIPSES:
    -1999 TO +3000," NASA Technical Publication TP-2006-214141

    Revisions
    ---------
    20230202  y.yoshimura

    See also
    --------
    utc2tt, dat
    """
    jd = np.asarray(jd)
    scalar_input = jd.ndim == 0
    jd = np.atleast_1d(jd)

    # Calculate year from Julian day
    year = 2000.0 + (jd - 2451545.0) / 365.25

    dt = np.zeros_like(jd)

    for i in range(len(jd)):
        if 1620.5 < year[i] < 2019.5:
            # Interpolation from table
            x = int(np.floor(year[i] - 1620.0 + 0.5))
            a = _DELTA_T_DATA[x + 1, 1] - _DELTA_T_DATA[x, 1]
            b = _DELTA_T_DATA[x + 2, 1] - _DELTA_T_DATA[x + 1, 1]
            c = b - a
            n = year[i] - _DELTA_T_DATA[x + 1, 0]
            dt[i] = _DELTA_T_DATA[x + 1, 1] + (a + b + n * c) * n / 2.0

        elif year[i] < 2050.0:
            u = (year[i] - 2000.0) / 100.0
            dt[i] = 60.94 + u * (32.217 + u * 55.89)

        elif year[i] < 2150.0:
            u = (year[i] - 1820.0) / 100.0
            dt[i] = -207.69 + u * (56.28 + u * 32.0)

        else:
            u = (year[i] - 1820.0) / 100.0
            dt[i] = -20.0 + 32.0 * u * u

    if scalar_input:
        return float(dt[0])
    return dt


