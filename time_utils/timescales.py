def s2day(s: float | np.ndarray) -> float | np.ndarray:
    """
    # transform second to days

    Parameters
    ----------
    s : float or np.ndarray
        time in seconds

    Returns
    -------
    day : float or np.ndarray
        time in days
    """
    return s / 86400.0


def utc2tt(jd_utc: float | np.ndarray, delta_at: float | np.ndarray) -> float | np.ndarray:
    """
    # UTC to TT (Terrestrial time)

    Parameters
    ----------
    jd_utc : float or np.ndarray
        Julian day in UTC, day
    delta_at : float or np.ndarray
        dAT (TAI - UTC), seconds

    Returns
    -------
    jd_tt : float or np.ndarray
        Julian date of TT, day

    Notes
    -----
    TT = TAI + 32.184
       = UTC + delta_AT + 32.184

    References
    ----------
    Vallado, D. A., & McClain, W. D. (2001). Fundamentals of Astrodynamics
    and Applications. Springer Science & Business Media. p.220

    Revisions
    ---------
    20230612  y.yoshimura

    See also
    --------
    dat, leap_s
    """
    jd_tai = jd_utc + s2day(delta_at)
    jd_tt = jd_tai + s2day(32.184)

    return jd_tt


